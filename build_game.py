# Builds docs/game/levels.js and docs/game/layout.js for "Fill the Hole" from plain JSON:
#
#     docs/game/maps/<key>.json   one file per map (see mapio.py for the accepted graph forms)
#     docs/game/levels.json       the level list, in play order, and the islands of the level map
#
#   python3 docs/game/build_game.py                 build everything (reuses cached layouts and world maps)
#   python3 docs/game/build_game.py --suggest KEY   rank start states of map KEY by difficulty, per par (to write levels)
#   python3 docs/game/build_game.py --ladder KEY    print ready-to-paste level entries, one per par, easiest first
#   python3 docs/game/build_game.py --check KEY     validate one map JSON and print its hole statistics
#   python3 docs/game/build_game.py --fresh         recompute every layout and world map
#
# Adding a map: drop a JSON file into maps/ ({"name", "hole", and faces | rot | ascii | edges+pos}), run --check and
# --ladder on it, paste the levels you like into levels.json, then build. Only new or changed maps are laid out
# (that step needs numpy, scipy and torch; the world map, "world": true, also needs scikit-learn).
#
# All game logic comes from kempe_engine.py (pure Python). Each level's start is either given ("pick": {"start": ...})
# or chosen by constraints ("pick": {"dF": 3, "onLoop": true, ...}); "expect" facts are asserted, so the level texts
# cannot drift from the maths.
import os, sys, json, hashlib, argparse, collections

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from kempe_engine import HoleGame  # noqa: E402
from mapio import load_map, link_word  # noqa: E402

MAPS = os.path.join(HERE, 'maps')


def read_js(path):
    if not os.path.exists(path): return {}
    s = open(path).read(); return json.loads(s[s.index('{'):s.rindex('}') + 1])


def write_js(path, var, obj, note):
    with open(path, 'w') as f:
        f.write('// Generated by docs/game/build_game.py from %s. Do not edit.\n' % note)
        f.write('window.%s = %s;\n' % (var, json.dumps(obj, separators=(',', ':'), ensure_ascii=False)))


# ----------------------------------------------------------------------------------------------------------- maps
class Board:
    """one map: its graph, the engine, and the drawing data the page needs"""

    def __init__(self, key):
        self.key = key
        self.spec = json.load(open(os.path.join(MAPS, key + '.json')))
        sp = self.spec
        self.rot, self.tri = load_map(sp)
        self.n = len(self.rot); self.h = sp['hole']
        assert 0 <= self.h < self.n, key + ': hole out of range'
        self.onboard = bool(sp.get('onboard'))
        self.ncol = sp.get('ncol', 4)
        if self.onboard:
            import math
            P = sp['pos']; ang = lambda w: math.atan2(P[w][1] - P[self.h][1], P[w][0] - P[self.h][0])
            self.link = sorted(self.rot[self.h], key=lambda w: (ang(w) + math.pi / 2) % (2 * math.pi))
            self.pos = [[round(x, 4), round(y, 4)] for x, y in P]
        else:
            assert self.tri, key + ': game maps must be triangulations (or onboarding ponds with "onboard": true)'
            from hole_layout import layout
            self.seed = sp.get('layoutSeed', 1)
            # pos: the straight-line drawing the graph skins (Dots, Spheres, ...) start from; drawSeed picks a
            # different drawing when the default one is cramped (set automatically by check_drawings)
            self.pos, self.link, _ = layout(self.rot, self.h, seed=sp.get('drawSeed', self.seed))
        adj = [list(r) for r in self.rot]
        self.H = HoleGame(self.n, adj, self.h, self.link, ncol=self.ncol, goal=sp.get('goal'))
        H = self.H
        self.dl = H.dl if hasattr(H, 'dl') else [False] * H.S
        self.H.Nch = H.N                       # name used by world_map.py
        self.loops = H.pi_cycles() if hasattr(H, 'dl') else []
        self.on_loop = {k: i for i, c in enumerate(self.loops) for k in c}
        self.sig = hashlib.sha1(json.dumps([self.rot, self.h, self.ncol, sp.get('goal'), self.pos if self.onboard else 0]).encode()).hexdigest()[:12]

    def colouring(self, k): return list(self.H.states[k])
    def canon(self, c): return self.H.canon(c)

    def summary(self):
        H = self.H; U = H.S - sum(H.filled)
        s = '%s: %s, %d regions, hole %d' % (self.key, self.spec.get('name', ''), self.n, self.h)
        if self.ncol == 4 and len(self.link) == 5: s += ' (ring %s)' % link_word(self.rot, self.h)
        s += '\n  %d colourings (up to renaming), %d Kempe classes, %d fillable (%.0f%%), deepest %d swaps' % (
            H.S, len(H.classes), H.S - U, 100 * (H.S - U) / H.S, max(H.dF))
        if hasattr(H, 'dl'):
            s += '\n  %d doubly locked, π loops: %s' % (sum(H.dl), [len(c) for c in self.loops] or 'none')
        cnt = collections.Counter(d for d in H.dF if d > 0)
        s += '\n  states by par: ' + ', '.join('%d: %d' % (d, cnt[d]) for d in sorted(cnt))
        return s

    # ---------------------------------------------------------------------------------------------- level picking
    def stats(self, k):
        H = self.H; best = H.best_moves(k); wins = [m for m in H.moves[k] if H.filled[m[0]]]
        st = {'dF': H.dF[k], 'N': H.N[k], 'difficulty': H.difficulty(k),
              'shortWin': min((m[1] for m in wins), default=99), 'fewWins': len(wins), 'moves': len(H.moves[k])}
        if hasattr(H, 'dl'):
            st.update(dl=H.dl[k], locks=H.locks(k), onLoop=k in self.on_loop, piRule=H.pi_rule(k),
                      quietOnly=bool(best) and all(m[2] == 0 for m in best),
                      loudOnly=bool(best) and all(m[2] > 0 and m[0] != H.pi[k] for m in best),
                      piOnly=bool(best) and all(m[0] == H.pi[k] for m in best))
        return st

    def matches(self, k, p):
        H = self.H
        if H.filled[k] or H.dF[k] < 0: return False
        st = self.stats(k)

        def rng(v, want):
            return want[0] <= v <= want[1] if isinstance(want, list) else v == want
        for f in ('dF', 'N', 'locks'):
            if f in p and not rng(st[f], p[f]): return False
        if 'dl' in p and st['dl'] != p['dl']: return False
        if 'onLoop' in p and st['onLoop'] != p['onLoop']: return False
        if 'exits' in p and not st[p['exits']]: return False
        if p.get('deepest') and H.dF[k] != max(H.dF): return False
        if 'piRule' in p:
            pr = st['piRule']; want = p['piRule']
            ok = (pr is None) if want == 'loops' else (pr == H.dF[k]) if want == 'par' else (pr is not None and pr > H.dF[k])
            if not ok: return False
        return True

    def pick(self, p):
        if 'start' in p:
            k = self.H.index.get(self.canon(p['start']))
            assert k is not None, '%s: start colouring is not a proper colouring of this map' % self.key
            return k
        ks = [k for k in range(self.H.S) if self.matches(k, p)]
        assert ks, '%s: no state matches %s' % (self.key, p)
        def key(k):
            st = self.stats(k); out = []
            for pr in p.get('prefer', []):
                sgn, f = (-1 if pr[0] == '-' else 1), pr.lstrip('+-')
                out.append(sgn * st[f])
            return out + [self.H.keys[k]]
        return min(ks, key=key)

    def pi_run(self, k, pred):
        out, seen = [], set()
        while k is not None and pred(k) and k not in seen:
            seen.add(k); out.append(k); k = self.H.pi[k]
        return out

    def record_run(self):
        """the longest π-run of doubly locked states with N <= 9 (the near-rigid runs of NRC)"""
        H = self.H; best = []
        for k in range(H.S):
            if H.dl[k] and H.N[k] <= 9:
                r = self.pi_run(k, lambda x: H.dl[x] and H.N[x] <= 9)
                if len(r) > len(best): best = r
        return best

    def export(self):
        H = self.H
        edges = sorted({(min(u, w), max(u, w)) for u in range(self.n) for w in self.rot[u]})
        g = {'name': self.spec.get('name', self.key), 'n': self.n, 'hole': self.h, 'link': self.link, 'pos': self.pos,
             'edges': [list(e) for e in edges], 'deg': [len(r) for r in self.rot], 'rot': self.rot, 'S': H.S,
             'dist': {H.keys[k]: H.dF[k] for k in range(H.S) if not H.filled[k] and H.dF[k] >= 0}}
        if self.onboard: g.update(ncol=self.ncol, goal=H.goal, onboard=True)
        elif self.ncol != 4 or H.goal != 3: g.update(ncol=self.ncol, goal=H.goal)
        return g


def lay_out(b, bad=0.3, seeds=range(2, 9)):
    """region shapes for map b; if the tiles come out uneven (area CV > bad), retry the drawing with other seeds,
    keep the best, and write the winning seed into the map JSON (as layoutSeed)"""
    from build_layout import build as build_layout
    from hole_layout import layout
    pos0 = b.pos if b.spec.get('drawSeed', b.seed) == b.seed else layout(b.rot, b.h, seed=b.seed)[0]
    best = build_layout(b.rot, b.h, pos0); seed = b.seed
    if best['cv'] > bad:
        for sd in seeds:
            if sd == b.seed: continue
            try: pos, link, _ = layout(b.rot, b.h, seed=sd)
            except AssertionError: continue
            r = build_layout(b.rot, b.h, pos)
            print('  seed %d: tile area CV %.3f' % (sd, r['cv']))
            if r['cv'] < best['cv']: best, seed = r, sd
            if best['cv'] <= bad: break
        if seed != b.seed:
            path = os.path.join(MAPS, b.key + '.json'); txt = open(path).read()
            assert '"layoutSeed"' not in txt
            open(path, 'w').write(txt.replace('\n  "hole":', '\n  "layoutSeed": %d,\n  "hole":' % seed, 1))
            b.seed = seed; print('  %s: using layout seed %d (saved in maps/%s.json)' % (b.key, seed, b.key))
    return best


def check_drawings(B, graphs, seeds=range(1, 31)):
    """run the Dots skin's own layout (tools/drawing_check.js, needs node) on every map; for a map whose final
    drawing is cramped (not "good": dots too close, or many left off the lattice), try other drawing seeds and save
    the first good one (else the roomiest) as drawSeed in the map JSON"""
    import subprocess, shutil, tempfile
    if not shutil.which('node'): print('(node not found: skipping the drawing check)'); return False
    chk = os.path.join(HERE, 'tools', 'drawing_check.js'); changed = False
    run = lambda *a: [json.loads(l) for l in subprocess.run(['node', chk, *a], capture_output=True, text=True).stdout.split('\n') if l.strip()]
    from hole_layout import layout
    for r in run():
        b = B.get(r['key'])
        if r['good'] or b is None or b.onboard: continue
        print('drawing for %s is cramped in the graph skins (spread %.3f); trying other seeds' % (b.key, r['spread']))
        best = (r['spread'], b.spec.get('drawSeed', b.seed), None)
        for sd in seeds:
            try: pos = layout(b.rot, b.h, seed=sd)[0]
            except AssertionError: continue
            with tempfile.NamedTemporaryFile('w', suffix='.json', delete=False) as f: json.dump(pos, f)
            q = run(b.key, f.name)[0]; os.unlink(f.name)
            if q['good'] or q['spread'] > best[0]: best = (q['spread'] + (9 if q['good'] else 0), sd, pos)
            if q['good']: break
        if best[2] is None: print('  %s: no better seed in %s' % (b.key, list(seeds))); continue
        sd, pos = best[1], best[2]
        path = os.path.join(MAPS, b.key + '.json'); txt = open(path).read()
        if 'drawSeed' in b.spec: txt = txt.replace('\n  "drawSeed": %d,' % b.spec['drawSeed'], '')
        open(path, 'w').write(txt.replace('\n  "hole":', '\n  "drawSeed": %d,\n  "hole":' % sd, 1))
        b.spec['drawSeed'] = sd; graphs[b.key]['pos'] = pos; changed = True
        print('  %s: drawing seed %d%s (saved in maps/%s.json)' % (b.key, sd, '' if best[0] >= 9 else ' (best found, still tight)', b.key))
    return changed


def check_expect(b, k, L):
    H = b.H; ex = L.get('expect', {}); lid = L['id']
    if 'par' in ex: assert H.dF[k] == ex['par'], '%s: par %d, expected %d' % (lid, H.dF[k], ex['par'])
    if ex.get('onLoop'): assert k in b.on_loop, lid + ': start is not on a π loop'
    if 'loopLength' in ex:
        assert b.loops and all(len(c) == ex['loopLength'] for c in b.loops), '%s: loop lengths %s' % (lid, [len(c) for c in b.loops])
    if 'loops' in ex: assert len(b.loops) == ex['loops'], '%s: %d loops' % (lid, len(b.loops))
    if 'N' in ex: assert H.N[k] == ex['N'], lid + ': N'
    if ex.get('deepest'): assert H.dF[k] == max(H.dF), lid + ': not the deepest state'
    if ex.get('unique'): assert sum(1 for d in H.dF if d == H.dF[k]) == 1, lid + ': not the only state at this depth'
    if 'piRunN' in ex:
        run = b.record_run()
        assert run[0] == k and [H.N[x] for x in run] == ex['piRunN'], '%s: record run %s' % (lid, [H.N[x] for x in run])


# ------------------------------------------------------------------------------------------------------ the build
def build(fresh=False):
    spec = json.load(open(os.path.join(HERE, 'levels.json')))
    keys = []
    for L in spec['levels']:
        if L['map'] not in keys: keys.append(L['map'])
    ids = [L['id'] for L in spec['levels']]
    assert len(set(ids)) == len(ids), 'duplicate level id'
    B = {}
    for key in keys:
        B[key] = Board(key); print(B[key].summary())
    levels = []
    for L in spec['levels']:
        b = B[L['map']]; k = b.pick(L['pick']); check_expect(b, k, L)
        st = b.stats(k)
        levels.append({'id': L['id'], 'num': L['num'], 'g': L['map'], 'title': L['title'], 'kicker': L['kicker'],
                       'intro': L['intro'], 'tools': L.get('tools', []),
                       'start': list(L['pick']['start']) if 'start' in L['pick'] else [-1 if u == b.h else x for u, x in enumerate(b.colouring(k))],
                       'par': b.H.dF[k], 'dl': bool(st.get('dl', False)), 'N': b.H.N[k]})
        L['_k'] = k
        print('level %-5s %-16s %-8s par %d  N %2d  difficulty %5.2f%s' % (L['num'], L['id'], L['map'], b.H.dF[k], b.H.N[k], st['difficulty'],
              '  on a π loop' if st.get('onLoop') else ''))
    old_g = read_js(os.path.join(HERE, 'levels.js')).get('graphs', {})
    old_lay = read_js(os.path.join(HERE, 'layout.js'))
    graphs, lay = {}, {}
    for key, b in B.items():
        g = b.export()
        og = old_g.get(key, {})
        same = (og.get('rot') == b.rot and og.get('hole') == b.h)          # caches from before signatures existed
        # region shapes
        ol = old_lay.get(key)
        if b.onboard:                                            # ponds: hand-drawn centres, shapes made from the drawing
            from mapio import pond_cells
            lay[key] = {'border': [], 'arcs': {}, 'centre': b.pos, 'onboard': True, 'cells': pond_cells(b.pos, b.rot)}
        elif not fresh and ol and (ol.get('sig') == b.sig or (same and 'sig' not in ol)):
            lay[key] = ol
        else:
            print('laying out', key, '(a minute or two)')
            lay[key] = lay_out(b)
            g['pos'] = b.pos
        lay[key]['sig'] = b.sig
        # world map (optional)
        if b.spec.get('world') and not b.onboard:
            ow = og.get('world')
            if not fresh and ow and (ow.get('sig') == b.sig or (same and 'sig' not in ow)):
                w = ow
            else:
                print('world map for', key, '(t-SNE, a few minutes)')
                from world_map import world
                w = world(b, [])
                w['canon'] = ''.join(b.H.keys)                      # world order = engine order
            w['sig'] = b.sig
            # world order may differ from engine order (cached worlds): map through the canon strings
            m = b.n - 1; wi = {w['canon'][i * m:(i + 1) * m]: i for i in range(w['S'])}
            w['signs'] = [{'k': wi[b.H.keys[L['_k']]], 'name': L['title'],
                           'text': 'Start of level "%s": %d flips from the nearest fillable rim.' % (L['title'], b.H.dF[L['_k']])}
                          for L in spec['levels'] if L['map'] == key]
            if b.loops:
                w['trail'] = {'name': 'π loop', 'states': [wi[b.H.keys[x]] for x in b.loops[0]], 'closed': True,
                              'text': 'An all-doubly-locked π %d-cycle at this hole: following π returns here after %d flips.' % (len(b.loops[0]), len(b.loops[0]))}
            elif hasattr(b.H, 'dl'):
                run = b.record_run()
                if len(run) >= 6:
                    w['trail'] = {'name': '9-8 run' if len(run) == 8 else 'near-rigid run', 'states': [wi[b.H.keys[x]] for x in run], 'closed': False,
                                  'text': 'The longest near-rigid π-run at this hole: %d doubly locked states, chain count %s.' % (
                                      len(run), ', '.join(str(b.H.N[x]) for x in run[:4]) + ', …')}
                else: w.pop('trail', None)
            g['world'] = w
        graphs[key] = g
    for L in spec['levels']: L.pop('_k', None)
    out = {'graphs': graphs, 'levels': levels, 'islands': spec.get('islands', {}), 'legacy': spec.get('legacy', [])}
    write_js(os.path.join(HERE, 'levels.js'), 'GAME', out, 'levels.json and maps/*.json')
    write_js(os.path.join(HERE, 'layout.js'), 'LAYOUT', lay, 'maps/*.json')
    if check_drawings(B, graphs):
        write_js(os.path.join(HERE, 'levels.js'), 'GAME', out, 'levels.json and maps/*.json')
    print('wrote levels.js (%d levels, %d maps) and layout.js' % (len(levels), len(graphs)))
    import subprocess                                            # every map's shapes must match its graph exactly
    r = subprocess.run([sys.executable, os.path.join(HERE, 'tools', 'cells_check.py')], capture_output=True, text=True)
    assert r.returncode == 0, 'region shapes do not match the graph:\n' + r.stdout


# ------------------------------------------------------------------------------------------------- authoring tools
def suggest(key, top=4):
    b = Board(key); print(b.summary())
    H = b.H; byd = collections.defaultdict(list)
    for k in range(H.S):
        if not H.filled[k] and H.dF[k] > 0: byd[H.dF[k]].append(k)
    for d in sorted(byd):
        ks = sorted(byd[d], key=lambda k: (H.difficulty(k), H.keys[k]))
        picks = ks[:top // 2] + ks[-(top - top // 2):] if len(ks) > top else ks
        print('par %d: %d states, difficulty %.2f .. %.2f' % (d, len(ks), H.difficulty(ks[0]), H.difficulty(ks[-1])))
        for k in picks:
            st = b.stats(k)
            tags = [t for t in ('dl', 'onLoop', 'quietOnly', 'loudOnly', 'piOnly') if st.get(t)]
            print('   difficulty %5.2f  N %2d  moves %2d  winning first moves %d  π-rule %s  %s' % (
                st['difficulty'], st['N'], st['moves'], st['fewWins'], st.get('piRule', '-'), ' '.join(tags)))


def ladder(key):
    """one level per par: the easiest state at par 1, then the hardest state at every larger par"""
    b = Board(key); H = b.H; out = []
    pars = sorted({d for d in H.dF if d > 0})
    for d in pars:
        pref = ['+difficulty'] if d == 1 else ['-difficulty']
        k = b.pick({'dF': d, 'prefer': pref})
        st = b.stats(k)
        out.append({'id': '%s-%d' % (key, d), 'num': '?', 'map': key, 'kicker': 'Warm-up' if d == 1 else 'Depths',
                    'title': '%s, %d swap%s' % (b.spec.get('name', key), d, '' if d == 1 else 's'), 'tools': ['locks', 'pi'] if d > 1 else ['locks'],
                    'intro': 'Write the story here.', 'pick': {'dF': d, 'prefer': pref}, 'expect': {'par': d},
                    '_stats': {f: st[f] for f in ('difficulty', 'N', 'fewWins') if f in st}})
    for L in out: print(json.dumps(L, ensure_ascii=False) + ',')


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description='Build Fill the Hole levels from maps/*.json and levels.json')
    ap.add_argument('--suggest'); ap.add_argument('--ladder'); ap.add_argument('--check'); ap.add_argument('--fresh', action='store_true')
    a = ap.parse_args()
    if a.suggest: suggest(a.suggest)
    elif a.ladder: ladder(a.ladder)
    elif a.check: print(Board(a.check).summary())
    else: build(a.fresh)
