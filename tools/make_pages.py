#!/usr/bin/env python3
"""Builds the plain reading pages of 4square.studio: about, how-to-play, levels, four-colour-theorem, privacy, terms,
contact, plus sitemap.xml. Each page body is tools/pages/<name>.html (first line: <!-- title | description -->); the
level guide is written from levels.json and maps/*.json, so it never drifts from the game. Run after changing a
page or a level:  python3 tools/make_pages.py"""
import html, json, os, re, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = 'https://4square.studio/'
NAV = [('how-to-play.html', 'How to play'), ('levels.html', 'Levels'), ('four-colour-theorem.html', 'The maths'),
       ('about.html', 'About')]
FOOT = [('about.html', 'About'), ('contact.html', 'Contact'), ('privacy.html', 'Privacy'), ('terms.html', 'Terms'),
        ('https://github.com/kylemath/4Square', 'Source code')]
ORDER = ['how-to-play', 'levels', 'four-colour-theorem', 'about', 'contact', 'privacy', 'terms']

TEMPLATE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<meta name="description" content="{desc}">
<link rel="canonical" href="{url}">
<meta name="google-adsense-account" content="ca-pub-7680225514669783">
<meta name="theme-color" content="#2a7fdc">
<link rel="icon" type="image/png" sizes="192x192" href="icons/icon-192.png">
<link rel="stylesheet" href="site.css">
</head>
<body>
<!-- Generated by tools/make_pages.py from tools/pages/{name}.html. Edit that file, not this one. -->
<header class="site"><div class="in">
<a class="brand" href="./"><b>4</b>square</a>
<nav aria-label="Site">{nav}</nav>
<a class="play" href="./">Play ▶</a>
</div></header>
<main>
{body}
</main>
<footer class="site"><div class="in">{foot}<span>© {year} Kyle Mathewson</span></div></footer>
</body>
</html>
"""


def page(name, title, desc, body):
    cur = name + '.html'
    nav = ''.join(f'<a href="{h}"' + (' aria-current="page"' if h == cur else '') + f'>{t}</a>' for h, t in NAV)
    foot = ''.join(f'<a href="{h}">{t}</a>' for h, t in FOOT)
    out = TEMPLATE.format(title=html.escape(title), desc=html.escape(desc, quote=True), url=SITE + cur, name=name,
                          nav=nav, foot=foot, body=body.strip(), year=datetime.date.today().year)
    with open(os.path.join(ROOT, cur), 'w') as f:
        f.write(out)


def regions(key):
    m = json.load(open(os.path.join(ROOT, 'maps', key + '.json')))
    if 'rot' in m: return len(m['rot'])
    if 'pos' in m: return len(m['pos'])
    return None


def level_guide():
    d = json.load(open(os.path.join(ROOT, 'levels.json')))
    isl, out, cur = d['islands'], [], None
    for lv in d['levels']:
        k = lv['kicker']
        if k != cur:
            if cur is not None: out.append('</section>')
            name, _, emoji = isl.get(k, [k, '', ''])
            out.append(f'<section class="island"><h2>{emoji} {html.escape(name)}</h2>')
            cur = k
        n = regions(lv['map'])
        par = (lv.get('expect') or {}).get('par')
        meta = []
        if n: meta.append(f'{n} regions')
        if par: meta.append(f'par {par} swap' + ('s' if par != 1 else ''))
        if 'locks' in (lv.get('tools') or []): meta.append('locks')
        if 'pi' in (lv.get('tools') or []): meta.append('π')
        out.append(f'<div class="lv"><h3><span class="n">{html.escape(lv["num"])}</span>{html.escape(lv["title"])}</h3>'
                   f'<div class="meta">{" · ".join(meta)}</div><p>{html.escape(lv.get("intro", ""))}</p></div>')
    out.append('</section>')
    return len(d['levels']), '\n'.join(out)


def main():
    nlev, guide = level_guide()
    for name in ORDER:
        src = open(os.path.join(ROOT, 'tools', 'pages', name + '.html')).read()
        head, body = src.split('\n', 1)
        title, desc = [s.strip() for s in re.match(r'<!--(.*)-->', head).group(1).split('|', 1)]
        body = body.replace('{{LEVELS}}', guide).replace('{{NLEVELS}}', str(nlev))
        desc = desc.replace('{{NLEVELS}}', str(nlev))
        page(name, title, desc, body)
    today = datetime.date.today().isoformat()
    urls = [SITE] + [SITE + n + '.html' for n in ORDER]
    with open(os.path.join(ROOT, 'sitemap.xml'), 'w') as f:
        f.write('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n')
        for u in urls: f.write(f'  <url><loc>{u}</loc><lastmod>{today}</lastmod></url>\n')
        f.write('</urlset>\n')
    print(f'wrote {len(ORDER)} pages ({nlev} levels in the guide) and sitemap.xml')


if __name__ == '__main__':
    main()
